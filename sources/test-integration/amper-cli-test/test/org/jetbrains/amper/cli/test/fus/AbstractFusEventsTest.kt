/**
 * End-to-end tests for the FUS events reported by the CLI.
 *
 * These tests run the real CLI with FUS enabled, and read the events back from the dump file that the CLI writes
 * when `KOTLIN_TOOLCHAIN_FUS_DUMP_FILE` is set.
 * Nothing is ever uploaded: `KOTLIN_TOOLCHAIN_FUS_SEND_ENABLED` is forced to false.
 */
@Tag("cli-test-group-fus")
abstract class AbstractFusEventsTest : CliTestBase() {

    /**
     * A temp dir outside the repository, for the fake home directories, the throw-away caches, and the projects
     * generated by `kotlin new` (which must not be nested in another project).
     */
    @TempDir
    lateinit var nonRepositoryTempDir: Path

    /**
     * Runs the CLI like [runCli] does, but with FUS recording enabled and the FUS events dumped to a file, so that
     * the reported events can be read from the returned [FusCliResult]. Nothing is ever sent to the FUS servers.
     *
     * The data collection [consent] is faked in a throw-away directory, so that the real consent of the user running
     * these tests is neither read nor modified.
     *
     * @param sharedCacheDir the shared cache dir to use instead of the one shared by all tests. Pass
     * [newIsolatedFusCacheDir] to get a pristine FUS cache, in particular a consent state that was never reported
     * yet. This is much slower for commands that need the caches, so only use it with cheap commands.
     */
    protected suspend fun runCliWithFus(
        projectDir: Path,
        vararg args: String,
        consent: TestConsent = TestConsent.Accepted,
        sharedCacheDir: Path? = null,
        expectedExitCode: Int? = 0,
        assertEmptyStdErr: Boolean = true,
        amperJvmArgs: List<String> = emptyList(),
        wrapperMode: WrapperMode = WrapperMode.Local,
        configureEnvironment: MutableMap<String, String>.() -> Unit = {},
    ): FusCliResult {
        consent.writeConsentFileIn(fakeUserHome)

        val eventsDumpFile = nonRepositoryTempDir / "fus-events-${UUID.randomUUID()}.txt"
        val allArgs = buildList {
            if (sharedCacheDir != null) {
                add("--shared-cache-dir=${sharedCacheDir.pathString}")
            }
            addAll(args)
        }
        val cliResult = runCli(
            projectDir,
            args = allArgs.toTypedArray(),
            expectedExitCode = expectedExitCode,
            assertEmptyStdErr = assertEmptyStdErr,
            wrapperMode = wrapperMode,
            // On macOS, the shared consent file location is derived from 'user.home' and cannot be set via the
            // environment, so we override the whole home dir. We do it on all OSes for consistent behavior.
            amperJvmArgs = amperJvmArgs + "-Duser.home=\"${fakeUserHome.absolutePathString()}\"",
            configureEnvironment = {
                put("KOTLIN_TOOLCHAIN_FUS_ENABLED", "true")
                put("KOTLIN_TOOLCHAIN_FUS_DUMP_FILE", eventsDumpFile.pathString)
                put("KOTLIN_TOOLCHAIN_FUS_SEND_ENABLED", "false")
                // where the shared JetBrains consent file is looked up (except on macOS, see 'user.home' above)
                put("XDG_DATA_HOME", fakeUserHome.pathString)
                put("APPDATA", fakeUserHome.pathString)

                // cleanup inherited environment variables to create a baseline for tests
                remove("KOTLIN_TOOLCHAIN_FUS_CALLING_IDE_PRODUCT_CODE")
                remove("KOTLIN_FROM_SOURCES")
                remove("KOTLIN_TOOLCHAIN_INTERNAL_USER")
                for (ciMarker in CiEnvVars) {
                    remove(ciMarker)
                }

                configureEnvironment()
            },
        )
        return FusCliResult(cliResult, eventsDumpFile)
    }

    /**
     * The home directory that the CLI under test sees, so that it doesn't read nor write the consent of the user
     * running these tests. There is one per test, because JUnit creates one test instance per test method.
     */
    private val fakeUserHome: Path by lazy { (nonRepositoryTempDir / "user-home").createDirectories() }

    protected fun newIsolatedFusCacheDir(): Path =
        (nonRepositoryTempDir / "shared-cache-${UUID.randomUUID()}").createDirectories()

    companion object {

        /** The `os_family` value reported in regular events for the current host. */
        @JvmStatic
        protected val expectedOsFamily: String = when (SystemInfo.CurrentHost.family) {
            OsFamily.Windows -> "windows"
            OsFamily.MacOs -> "macos"
            OsFamily.Linux -> "linux"
            OsFamily.FreeBSD -> "freebsd"
            OsFamily.Solaris -> "solaris"
        }

        /** The `cpu_arch` value reported for the current host. */
        @JvmStatic
        protected val expectedCpuArch: String = when (SystemInfo.CurrentHost.arch) {
            Arch.X64 -> "x86_64"
            Arch.Arm64 -> "arm64"
        }
    }
}

/**
 * The state of the data collection consent to fake for a test run.
 */
enum class TestConsent {
    Accepted,
    Rejected,

    /** No consent file at all, which is what a user who was never asked has. */
    NotAnswered,
    ;

    /**
     * Writes the JetBrains-wide consent file in the given [userAppDataHome], which is the fake home directory that the
     * CLI under test sees. Nothing is written for [NotAnswered], because the absence of the file is the point.
     *
     * The format and location mirror `JetBrainsConsent` in the `amper-fus-analytics` module. We write the file
     * directly instead of using the `data-collection-consent` command because that command cannot create the file.
     */
    fun writeConsentFileIn(userAppDataHome: Path) {
        val valueInFile = when (this) {
            Accepted -> "1"
            Rejected -> "0"
            NotAnswered -> return
        }
        val appDataRoot = if (OsFamily.current.isMac) userAppDataHome / "Library/Application Support" else userAppDataHome
        val consentFile = appDataRoot / "JetBrains/consentOptions/accepted"
        consentFile.createParentDirectories()
            .writeText("rsch.send.usage.stat:1.1:$valueInFile:${System.currentTimeMillis()}")
    }
}

