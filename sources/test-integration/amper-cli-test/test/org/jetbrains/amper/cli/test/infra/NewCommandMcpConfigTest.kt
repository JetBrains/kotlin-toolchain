    @Test
    fun `generated MCP configs are git-ignored`() = runSlowTest {
        val workDir = (nonRepositoryTempDir / "gitignore").createDirectories()
        runCli(
            workDir, "new", "myapp", "--target-platform=desktop", *allAgentOptions.toTypedArray(),
            wrapperMode = WrapperMode.GlobalIntrinsicVersion,
        )
        val gitignore = (workDir / "myapp/.gitignore").readText().lines()
        for (path in allConfigs) {
            assertContains(gitignore, "/$path", "generated MCP config $path should be git-ignored")
        }
    }

    @Test
    fun `Junie and pi configs are regular files with shared content and survive moving the project`() = runSlowTest {
        val projectDir = generate("--target-platform=desktop")
        val sharedConfig = (projectDir / ".mcp.json").readText()

        for (configPath in sharedSchemaConfigs) {
            val path = projectDir / configPath
            assertTrue(path.isRegularFile(), "Expected a regular file at $configPath")
            assertFalse(path.isSymbolicLink(), "$configPath should not require symlink privileges")
            assertEquals(sharedConfig, path.readText(), configPath)
        }

        val movedDir = projectDir.moveTo(nonRepositoryTempDir / "moved")
        for (configPath in sharedSchemaConfigs) {
            assertEquals(sharedConfig, (movedDir / configPath).readText(), configPath)
        }
    }

    @ParameterizedTest
    @ValueSource(strings = ["--target-platform=desktop", "--target-platform=ios", "--from-template=jvm-cli"])
    fun `no-ai omits all MCP configs`(sourceOption: String) = runSlowTest {
        val projectDir = generate(sourceOption, "--no-ai")

        for (path in allConfigs) {
            assertFalse((projectDir / path).exists(), "$path should not be generated with --no-ai")
        }
        assertFalse((projectDir / "AGENTS.md").exists(), "AGENTS.md should not be generated with --no-ai")
    }

    @ParameterizedTest
    @ValueSource(
        strings = [
            "--target-platform=ios", "--target-platform=android", "--target-platform=web",
            "--target-platform=server", "--from-template=jvm-cli",
        ]
    )
    fun `projects without a JVM Compose app get only klibs MCP configs`(sourceOption: String) = runSlowTest {
        val projectDir = generate(sourceOption)

        for (path in allConfigs) {
            val config = (projectDir / path).readText()
            assertTrue("https://api.klibs.io/mcp" in config, "$path should include klibs for $sourceOption")
            assertFalse("compose-hot-reload" in config, "$path should omit hot reload for $sourceOption")
        }
    }

    @ParameterizedTest
    @ValueSource(strings = ["new", "init"])
    fun `repeated agent options generate configs only for selected agents`(command: String) = runSlowTest {
        val workDir = (nonRepositoryTempDir / command).createDirectories()
        val nameArgs = if (command == "new") ["myapp"] else []
        runCli(
            workDir, command, *nameArgs.toTypedArray(), "--target-platform=desktop",
            "--agent=antigravity", "--agent=junie", "--no-git",
            wrapperMode = WrapperMode.GlobalIntrinsicVersion,
        )
        val projectDir = if (command == "new") workDir / "myapp" else workDir
        val selectedConfigs = [".agents/mcp_config.json", ".junie/mcp/mcp.json"]
        for (path in allConfigs) {
            assertEquals(path in selectedConfigs, (projectDir / path).exists(), path)
        }
        assertTrue("klibs" in (projectDir / ".junie/mcp/mcp.json").readText())
    }

    @Test
    fun `duplicate agent options generate a single regular config`() = runSlowTest {
        val projectDir = generate("--target-platform=ios", "--agent=pi", "--agent=pi")
        for (path in allConfigs) {
            assertEquals(path == ".pi/mcp.json", (projectDir / path).exists(), path)
        }
        assertFalse((projectDir / ".pi/mcp.json").isSymbolicLink())
        assertTrue("https://api.klibs.io/mcp" in (projectDir / ".pi/mcp.json").readText())
    }

    @Test
    fun `non-interactive generation without agent options fails asking for agent or no-ai`() = runSlowTest {
        val workDir = (nonRepositoryTempDir / "no-agent-options").createDirectories()
        val result = runCli(
            workDir, "new", "myapp", "--target-platform=desktop", "--no-git",
            expectedExitCode = 1, assertEmptyStdErr = false,
            wrapperMode = WrapperMode.GlobalIntrinsicVersion,
        )
        result.assertStderrContains("Please specify which AI agents to configure with --agent")
        result.assertStderrContains("--no-ai")
        assertFalse((workDir / "myapp").exists())
    }

    @ParameterizedTest
    @CsvSource(
        value = [
            "${Agent.ClaudeCode.name}, .mcp.json",
            "${Agent.Codex.name}, .codex/config.toml",
            "${Agent.Antigravity.name}, .agents/mcp_config.json",
            "${Agent.Junie.name}, .junie/mcp/mcp.json",
            "${Agent.Pi.name}, .pi/mcp.json",
            "${Agent.OpenCode.name}, .opencode/opencode.json",
            "${Agent.GeminiCli.name},",
            "${Agent.Other.name},",
        ]
    )
    fun `non-interactive generation configures the detected agent`(agent: Agent, expectedConfig: String?) =
        runSlowTest {
            for (command in ["new", "init"]) {
                val workDir = (nonRepositoryTempDir / command).createDirectories()
                val nameArgs = if (command == "new") ["myapp"] else []
                runCliAsAgent(
                    agent, workDir, command, *nameArgs.toTypedArray(), "--target-platform=desktop", "--no-git",
                    wrapperMode = WrapperMode.GlobalIntrinsicVersion,
                )

                val projectDir = if (command == "new") workDir / "myapp" else workDir
                assertTrue((projectDir / "AGENTS.md").isRegularFile())
                for (path in allConfigs) {
                    assertEquals(path == expectedConfig, (projectDir / path).exists(), "$agent: $path")
                }
            }
        }

    @ParameterizedTest
    @ValueSource(strings = ["--no-ai", "--agent=claude", "--agent=other"])
    fun `explicit AI options override the detected agent`(option: String) = runSlowTest {
        for (command in ["new", "init"]) {
            val workDir = (nonRepositoryTempDir / command).createDirectories()
            val nameArgs = if (command == "new") ["myapp"] else []
            runCliAsAgent(
                Agent.Codex, workDir, command, *nameArgs.toTypedArray(),
                "--target-platform=desktop", "--no-git", option,
                wrapperMode = WrapperMode.GlobalIntrinsicVersion,
            )

            val projectDir = if (command == "new") workDir / "myapp" else workDir
            assertEquals(option != "--no-ai", (projectDir / "AGENTS.md").isRegularFile())
            for (path in allConfigs) {
                val expected = option == "--agent=claude" && path == ".mcp.json"
                assertEquals(expected, (projectDir / path).exists(), "$option: $path")
            }
        }
    }

    /** Generates a project, selecting all agents unless [options] already say which agents to use (or none). */
    private suspend fun generate(vararg options: String): Path {
        val workDir = (nonRepositoryTempDir / "work-${options.joinToString("")}").createDirectories()
        val agentOptions: List<String> =
            if (options.any { it == "--no-ai" || it.startsWith("--agent=") }) [] else allAgentOptions
        runCli(
            workDir, "new", "myapp", *options, *agentOptions.toTypedArray(), "--no-git",
            wrapperMode = WrapperMode.GlobalIntrinsicVersion,
        )
        return workDir / "myapp"
    }
}
