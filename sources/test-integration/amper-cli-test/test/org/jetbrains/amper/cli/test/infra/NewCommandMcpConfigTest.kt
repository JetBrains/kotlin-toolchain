            """.trimIndent(),
            (projectDir / ".mcp.json").readNormalizedText(),
        )
        assertEquals(
            if (windows) """
            {
              "mcpServers": {
                "compose-hot-reload": {
                  "command": "cmd",
                  "args": [
                    "/c",
