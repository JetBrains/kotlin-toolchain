                  ]
                },
                "klibs": {
                  "serverUrl": "https://api.klibs.io/mcp"
                }
              }
            }

            """.trimIndent(),
            (projectDir / ".agents/mcp_config.json").readNormalizedText(),
        )
        assertEquals(
            if (windows) $$"""
            {
              "$schema": "https://opencode.ai/config.json",
              "mcp": {
