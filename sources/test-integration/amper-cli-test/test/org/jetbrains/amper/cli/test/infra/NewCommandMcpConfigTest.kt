                  "url": "https://api.klibs.io/mcp"
                }
              }
            }

            """.trimIndent() else """
            {
              "mcpServers": {
                "compose-hot-reload": {
                  "command": "./kotlin",
                  "args": [
                    "compose-hot-reload-mcp-server"
                  ]
                },
                "klibs": {
                  "type": "http",
                  "url": "https://api.klibs.io/mcp"
                }
              }
